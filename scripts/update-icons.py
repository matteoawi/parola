"""Vendor a pinned, existing Lucide set; generate the shared renderer without drawing SVGs."""
import argparse,base64,hashlib,io,json,pathlib,re,tarfile,urllib.request

ROOT=pathlib.Path(__file__).resolve().parents[1]
VENDOR=ROOT/'assets/icons/lucide'
VERSION='1.56.0'
ALIASES={
 'write':'pencil-line','path':'route','grid':'layout-grid','tile':'layers-2',
 'pair':'copy-check','book':'book-open','review':'history','settings':'settings',
 'star':'star','spark':'sparkles','flame':'flame','speaker':'volume-2','ear':'ear',
 'arrow':'arrow-right','back':'arrow-left','down':'chevron-down','chevron':'chevron-right',
 'check':'check','close':'x','hint':'lightbulb','shuffle':'shuffle','undo':'undo-2',
 'complete':'list-checks','compose':'blocks','pen':'pencil','play':'play',
 'download':'download','upload':'upload','swap':'arrow-right-left','heart':'heart',
 'globe':'globe','trophy':'trophy','shield':'shield-check','clock':'clock',
 'alpha':'languages','info':'info',
}

def fetch(url):
 with urllib.request.urlopen(url,timeout=45) as response:return response.read()

def main():
 parser=argparse.ArgumentParser();parser.add_argument('--download',action='store_true');args=parser.parse_args()
 source=VENDOR/'sources.json'
 if args.download:
  metadata=json.loads(fetch(f'https://registry.npmjs.org/lucide-static/{VERSION}'))
  archive=fetch(metadata['dist']['tarball'])
  digest='sha512-'+base64.b64encode(hashlib.sha512(archive).digest()).decode()
  if digest!=metadata['dist']['integrity']:raise SystemExit('Upstream archive integrity mismatch')
  package=tarfile.open(fileobj=io.BytesIO(archive),mode='r:gz')
  files={name:package.extractfile(f'package/icons/{name}.svg').read() for name in sorted(set(ALIASES.values()))}
  license_text=package.extractfile('package/LICENSE').read()
  VENDOR.mkdir(parents=True,exist_ok=True)
  for name,data in files.items():(VENDOR/f'{name}.svg').write_bytes(data)
  (VENDOR/'LICENSE').write_bytes(license_text)
  provenance={'library':'Lucide','package':'lucide-static','version':VERSION,'repository':'https://github.com/lucide-icons/lucide','tarball':metadata['dist']['tarball'],'integrity':digest,'license':'ISC; inherited Feather icons under MIT','aliases':ALIASES,'sha256':{name:hashlib.sha256(data).hexdigest() for name,data in files.items()}}
  source.write_text(json.dumps(provenance,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
 provenance=json.loads(source.read_text(encoding='utf-8'))
 if provenance['aliases']!=ALIASES or provenance['version']!=VERSION:raise SystemExit('Pinned source mapping mismatch')
 originals={}
 for name,expected in provenance['sha256'].items():
  raw=(VENDOR/f'{name}.svg').read_bytes()
  if hashlib.sha256(raw).hexdigest()!=expected:raise SystemExit(f'Original modified: {name}')
  originals[name]=raw.decode('utf-8')
 license_text=(VENDOR/'LICENSE').read_text(encoding='utf-8')
 module='/* Generated by scripts/update-icons.py from lucide-static '+VERSION+'.\n'+license_text+'\n*/\n'
 module+='export const iconSources='+json.dumps(ALIASES,separators=(',',':'))+';\n'
 module+='const originalSVGs='+json.dumps(originals,ensure_ascii=False,separators=(',',':'))+';\n'
 module+='''export function icon(name,size=22,cls=''){
 const source=iconSources[name]||iconSources.spark;
 return originalSVGs[source].replace(/class="[^"]*"/,`class="lucide lucide-${source} ${cls}" data-icon="${source}" aria-hidden="true" focusable="false"`).replace('width="24"',`width="${size}"`).replace('height="24"',`height="${size}"`);
}
'''
 (ROOT/'src/icons.mjs').write_text(module,encoding='utf-8',newline='\n')
 # Preserve every original shape: only root sizing, colors and CSS surface change.
 favicon=originals['layers-2'].replace('width="24"','width="192"').replace('height="24"','height="192"').replace('stroke="currentColor"','stroke="#183f43"').replace('class="lucide lucide-layers-2"','class="lucide lucide-layers-2" style="background:#f18d74;border-radius:20%;padding:28px;box-sizing:border-box"')
 (ROOT/'icon.svg').write_text(favicon,encoding='utf-8',newline='\n')
 print(f'{len(ALIASES)} aliases, {len(originals)} original Lucide SVGs; renderer and app icon generated')

if __name__=='__main__':main()
